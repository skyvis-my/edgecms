export async function handleMcpToolCall(
  ctx: CommandContext,
  name: string,
  args: Record<string, unknown> = {}
): Promise<{ content: Array<{ type: 'text'; text: string }>; isError?: boolean }> {
  // A tenant-scoped endpoint never serves another tenant's content.
  const requestedTenant = typeof args.tenantId === 'string' ? args.tenantId : undefined
  if (ctx.tenantScope && requestedTenant && requestedTenant !== ctx.tenantScope) {
    return {
      content: [
        { type: 'text', text: 'Error: tenantId override is not allowed on a tenant-scoped MCP endpoint' },
      ],
      isError: true,
    }
  }
  // HS-14: the effective tenant (context or override) must have AI turned on.
  const effectiveTenant = ctx.tenantScope ?? requestedTenant
  if (!(await isTenantAiEnabled({ db: ctx.db, workerEnv: ctx.env, tenantId: effectiveTenant }))) {
    return { content: [{ type: 'text', text: `Error: ${AI_DISABLED_MESSAGE}` }], isError: true }
  }

  const tool = MCP_TOOLS.find((t) => t.name === name)
  const missing = (tool?.inputSchema.required ?? []).filter(
    (key) => args[key] === undefined || args[key] === null || args[key] === ''
  )
  if (missing.length > 0) {
    return {
      content: [{ type: 'text', text: `Error: missing required argument(s): ${missing.join(', ')}` }],
      isError: true,
    }
  }

  try {
    switch (name) {
      case 'edgecms_list_collections': {
        const tenantId = (args.tenantId as string | undefined) ?? ctx.tenantScope
        const collections = await collectionsRepository.findAll(ctx.db, tenantId)
        const sanitized = collections.map((col) => ({
          id: col.id,
          name: col.name,
          slug: col.slug,
          singleton: col.singleton,
          defaultLocale: col.defaultLocale,
          supportedLocales: col.supportedLocales,
          fieldCount: col.fields.length,
          fieldsSummary: col.fields.map((f) => ({ name: f.name, type: f.type, required: f.required })),
        }))
        return {
          content: [{ type: 'text', text: JSON.stringify(sanitized, null, 2) }],
        }
      }

      case 'edgecms_get_schema': {
        const collectionSlug = args.collectionSlug as string
        const tenantId = (args.tenantId as string | undefined) ?? ctx.tenantScope
        const collection = await collectionsRepository.findBySlug(ctx.db, collectionSlug, tenantId)
        if (!collection) {
          return {
            content: [{ type: 'text', text: `Collection '${collectionSlug}' not found` }],
            isError: true,
          }
        }
        return {
          content: [{ type: 'text', text: JSON.stringify(collection, null, 2) }],
        }
      }

      case 'edgecms_list_entries': {
        const collectionSlug = args.collectionSlug as string
        const tenantId = (args.tenantId as string | undefined) ?? ctx.tenantScope
        const collection = await collectionsRepository.findBySlug(ctx.db, collectionSlug, tenantId)
        if (!collection) {
          return {
            content: [{ type: 'text', text: `Collection '${collectionSlug}' not found` }],
            isError: true,
          }
        }
        const page = Math.max(1, Number(args.page) || 1)
        const perPage = Math.min(100, Math.max(1, Number(args.perPage) || 20))
        const status = args.status as string | undefined

        const entriesResult = await entriesRepository.findAll(ctx.db, {
          collectionId: collection.id,
          tenantId,
          page,
          perPage,
          status,
        })
        return {
          content: [{ type: 'text', text: JSON.stringify(entriesResult, null, 2) }],
        }
      }

      case 'edgecms_get_entry': {
        const entryId = args.entryId as string
        const tenantId = (args.tenantId as string | undefined) ?? ctx.tenantScope
        const entry = await entriesRepository.findById(ctx.db, entryId, tenantId)
        if (!entry) {
          return {
            content: [{ type: 'text', text: `Entry '${entryId}' not found` }],
            isError: true,
          }
        }
        return {
          content: [{ type: 'text', text: JSON.stringify(entry, null, 2) }],
        }
      }

      case 'edgecms_preview_command': {
        const type = args.type as CommandType
        const payload = (args.payload as Record<string, unknown>) || {}
        const optimisticVersion = args.optimisticVersion as number | undefined

        const envelope: CommandEnvelope = {
          type,
          payload,
          optimisticVersion,
          actor: {
            userId: ctx.actor.userId,
            source: 'ai',
          },
          dryRun: true,
          timestamp: new Date().toISOString(),
        }

        // Execute dry-run preview through the Command Engine
        const result = await executeCommand(ctx, envelope)

        // Generate an immutable preview receipt
        const receipt = await createPreviewReceipt({
          commands: [envelope],
          userId: ctx.actor.userId,
          tenantId: ctx.tenantScope,
          kv: ctx.kv,
        })

        return {
          content: [
            {
              type: 'text',
              text: JSON.stringify(
                {
                  status: 'dry_run',
                  commandType: type,
                  diff: result.diff,
                  previewReceipt: receipt.receiptId,
                  sha256Hash: receipt.hash,
                  expiresAt: receipt.expiresAt,
                  message:
                    'Dry-run preview completed successfully. To execute these mutations, call edgecms_execute_command with this previewReceipt.',
                },
                null,
                2
              ),
            },
          ],
        }
      }

      case 'edgecms_execute_command': {
        const previewReceiptId = args.previewReceipt as string
        if (!previewReceiptId) {
          return {
            content: [{ type: 'text', text: 'Error: previewReceipt is required to execute a command' }],
            isError: true,
          }
        }

        // Verify the immutable preview receipt
        const verification = await verifyPreviewReceipt({
          receiptId: previewReceiptId,
          userId: ctx.actor.userId,
          tenantId: ctx.tenantScope,
          kv: ctx.kv,
          commandsToVerify: args.command ? [args.command as CommandEnvelope] : undefined,
        })

        if (!verification.valid || !verification.receipt) {
          return {
            content: [
              {
                type: 'text',
                text: `Preview receipt verification failed: ${verification.message ?? verification.error}`,
              },
            ],
            isError: true,
          }
        }

        if (!verification.receipt.commands || verification.receipt.commands.length === 0) {
          return {
            content: [{ type: 'text', text: 'Preview receipt contains no staged commands' }],
            isError: true,
          }
        }

        const results: CommandResult[] = []
        if (verification.receipt.commands.length === 1) {
          const stagedCommand = verification.receipt.commands[0]!
          const executionEnvelope: CommandEnvelope = {
            ...stagedCommand,
            dryRun: false,
            previewReceipt: previewReceiptId,
            timestamp: new Date().toISOString(),
          }

          const result = await executeCommand(ctx, executionEnvelope)
          results.push(result)

          if (result.status === 'failed') {
            return {
              content: [
                {
                  type: 'text',
                  text: JSON.stringify(
                    {
                      status: 'failed',
                      error: result.error,
                      commandId: result.commandId,
                      results,
                    },
                    null,
                    2
                  ),
                },
              ],
              isError: true,
            }
          }
        } else {
          // Multi-command receipts are executed as a single transaction envelope
          const txEnvelope: CommandEnvelope = {
            type: 'transaction',
            payload: {
              commands: verification.receipt.commands.map((cmd) => ({
                ...cmd,
                dryRun: false,
                previewReceipt: undefined,
              })),
            },
            dryRun: false,
            previewReceipt: previewReceiptId,
            actor: {
              userId: ctx.actor.userId,
              source: 'ai',
            },
            timestamp: new Date().toISOString(),
          }

          const txResult = await executeCommand(ctx, txEnvelope)
          if (txResult.status === 'failed') {
            return {
              content: [
                {
                  type: 'text',
                  text: JSON.stringify(
                    {
                      status: 'failed',
                      error: txResult.error,
                      commandId: txResult.commandId,
                      results: [txResult],
                    },
                    null,
                    2
                  ),
                },
              ],
              isError: true,
            }
          }
          const subResults = (txResult.data?.subResults as CommandResult[] | undefined) ?? [txResult]
          results.push(...subResults)
        }

        await markPreviewReceiptConsumed(previewReceiptId, ctx.kv, ctx.tenantScope)

        const finalData =
          results.length === 1
            ? {
                status: 'success',
                commandId: results[0]?.commandId,
                type: results[0]?.type,
                data: results[0]?.data,
                executedAt: results[0]?.executedAt,
              }
            : {
                status: 'success',
                results,
              }

        return {
          content: [
            {
              type: 'text',
              text: JSON.stringify(finalData, null, 2),
            },
          ],
        }
      }

      case 'edgecms_search_rag': {
        const query = args.query as string
        if (!query || typeof query !== 'string') {
          return {
            content: [{ type: 'text', text: 'Error: query is required for edgecms_search_rag' }],
            isError: true,
          }
        }
        const tenantId = (args.tenantId as string | undefined) ?? ctx.tenantScope
        const collectionSlug = args.collectionSlug as string | undefined
        const limit = Math.min(20, Math.max(1, Number(args.limit) || 5))

        const results = await ragService.searchRag({
          db: ctx.db,
          env: ctx.env,
          query,
          tenantId,
          collectionSlug,
          limit,
        })

        return {
          content: [{ type: 'text', text: JSON.stringify(results, null, 2) }],
        }
      }

      default:
        return {
          content: [{ type: 'text', text: `Unknown MCP tool: ${name}` }],
          isError: true,
        }
    }
  } catch (err) {
    const message = err instanceof Error ? err.message : String(err)
    return {
      content: [{ type: 'text', text: `Tool execution failed: ${message}` }],
      isError: true,
    }
  }
}

/** Protocol revisions this server speaks, newest first. */
export const MCP_SUPPORTED_PROTOCOL_VERSIONS = ['2025-06-18', '2025-03-26', '2024-11-05'] as const
export const MCP_LATEST_PROTOCOL_VERSION = MCP_SUPPORTED_PROTOCOL_VERSIONS[0]

/**
 * MCP version negotiation: answer with the client's requested version when we
 * support it, otherwise with our latest (the client then decides whether to continue).
 */
export function negotiateProtocolVersion(requested: unknown): string {
  return typeof requested === 'string' &&
    (MCP_SUPPORTED_PROTOCOL_VERSIONS as readonly string[]).includes(requested)
    ? requested
    : MCP_LATEST_PROTOCOL_VERSION
}

function isValidId(id: unknown): id is string | number | null {
  return id === null || typeof id === 'string' || typeof id === 'number'
}

/**
 * Handles one incoming JSON-RPC 2.0 message according to the Model Context Protocol.
 *
 * Returns `null` for messages that get no reply: notifications (no `id`) and
 * client responses (no `method`). The controller answers those with HTTP 202.
 */
export async function processMcpMessage(
  ctx: CommandContext,
  message: unknown
): Promise<McpJsonRpcResponse | null> {
  if (!message || typeof message !== 'object' || Array.isArray(message)) {
    return { jsonrpc: '2.0', id: null, error: { code: -32600, message: 'Invalid Request' } }
  }
  const request = message as Partial<McpJsonRpcRequest> & { result?: unknown; error?: unknown }
  const hasId = 'id' in request && request.id !== undefined

  // A client response to a server request: this server never sends requests.
  if (request.method === undefined && hasId && ('result' in request || 'error' in request)) {
    return null
  }
  if (request.jsonrpc !== '2.0' || typeof request.method !== 'string' || (hasId && !isValidId(request.id))) {
    return {
      jsonrpc: '2.0',
      id: hasId && isValidId(request.id) ? request.id : null,
      error: { code: -32600, message: 'Invalid Request' },
    }
  }
  // Notifications (e.g. notifications/initialized, notifications/cancelled) get no reply.
  if (!hasId) return null

  const id = request.id ?? null
  const method = request.method
  const params =
    request.params && typeof request.params === 'object' ? request.params : ({} as Record<string, unknown>)

  switch (method) {
    case 'initialize': {
      return {
        jsonrpc: '2.0',
        id,
        result: {
          protocolVersion: negotiateProtocolVersion(params.protocolVersion),
          capabilities: {
            tools: {},
          },
          serverInfo: {
            name: 'edgecms-mcp-server',
            version: '1.0.0',
          },
        },
      }
    }

    case 'tools/list': {
      return {
        jsonrpc: '2.0',
        id,
        result: {
          tools: MCP_TOOLS,
        },
      }
    }

    case 'tools/call': {
      const toolName = params.name
      const toolArgs =
        params.arguments && typeof params.arguments === 'object'
          ? (params.arguments as Record<string, unknown>)
          : {}
      if (!toolName || typeof toolName !== 'string') {
        return {
          jsonrpc: '2.0',
          id,
          error: {
            code: -32602,
            message: 'Missing "name" parameter in tools/call',
          },
        }
      }

      const toolResult = await handleMcpToolCall(ctx, toolName, toolArgs)
      return {
        jsonrpc: '2.0',
        id,
        result: toolResult,
      }
    }

    case 'ping': {
      return {
        jsonrpc: '2.0',
        id,
        result: {},
      }
    }

    default: {
      return {
        jsonrpc: '2.0',
        id,
        error: {
          code: -32601,
          message: `Method not found: ${method}`,
        },
      }
    }
  }
}
