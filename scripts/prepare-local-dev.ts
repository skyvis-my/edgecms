import { existsSync } from 'node:fs'
import { mkdir, readFile, writeFile } from 'node:fs/promises'
import { join } from 'node:path'

/**
 * Prepares a fresh checkout for `bun run dev:api`:
 * - `apps/api/.dev.vars` with generated local-only secrets (wrangler refuses to start auth without them)
 * - `apps/admin/dist` placeholder, because the Worker's static assets binding requires the directory
 *
 * Existing values are never overwritten.
 */

const apiDir = new URL('../apps/api', import.meta.url).pathname
const adminDistDir = new URL('../apps/admin/dist', import.meta.url).pathname

export const LOCAL_SUPER_ADMIN_EMAIL = 'smoke.admin@example.com'

function randomSecret() {
  return Buffer.from(crypto.getRandomValues(new Uint8Array(32))).toString('hex')
}

export function defaultDevVars(secret: () => string = randomSecret): Record<string, string> {
  return {
    BETTER_AUTH_SECRET: secret(),
    JWT_HS256_SECRET: secret(),
    SUPER_ADMIN_EMAILS: LOCAL_SUPER_ADMIN_EMAIL,
  }
}

export function parseDevVarKeys(content: string) {
  return new Set(
    content
      .split('\n')
      .map((line) => line.trim())
      .filter((line) => line && !line.startsWith('#') && line.includes('='))
      .map((line) => line.slice(0, line.indexOf('=')).trim())
  )
}

/** Returns the keys appended to `.dev.vars` (empty when nothing was missing). */
export async function ensureDevVars(
  path = join(apiDir, '.dev.vars'),
  defaults = defaultDevVars()
): Promise<string[]> {
  const existing = existsSync(path) ? await readFile(path, 'utf8') : ''
  const present = parseDevVarKeys(existing)
  const missing = Object.entries(defaults).filter(([key]) => !present.has(key))
  if (missing.length === 0) return []

  const header = existing ? '' : '# Local-only values generated by scripts/prepare-local-dev.ts\n'
  const separator = existing && !existing.endsWith('\n') ? '\n' : ''
  const lines = missing.map(([key, value]) => `${key}=${value}`).join('\n')
  await writeFile(path, `${existing}${separator}${header}${lines}\n`)
  return missing.map(([key]) => key)
}

/** Returns true when a placeholder admin build was created. */
export async function ensureAdminDist(dir = adminDistDir): Promise<boolean> {
  if (existsSync(join(dir, 'index.html'))) return false
  await mkdir(dir, { recursive: true })
  await writeFile(
    join(dir, 'index.html'),
    '<!doctype html><title>EdgeCMS API</title><p>The admin runs on <a href="http://localhost:5173">http://localhost:5173</a> during development. Run <code>bun run build:admin</code> to serve it from the Worker.</p>\n'
  )
  return true
}

export async function main() {
  const added = await ensureDevVars()
  if (added.length > 0) console.log(`prepare-local-dev: wrote ${added.join(', ')} to apps/api/.dev.vars`)
  if (await ensureAdminDist()) console.log('prepare-local-dev: created placeholder apps/admin/dist')
}

if (import.meta.main) {
  await main()
}
